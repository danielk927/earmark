#include "../beacons/beacon_core.h"
#include <cstdio>
#include <vector>

int main() {
  std::vector<uint32_t> words(105002);
  const size_t count = beacon::makeWave(1000, 20000, 10.0, words.data(), words.size());
  if (count != 105000) return 1;
  std::puts("// Generated by firmware/tests/generate_sweep.cpp; do not hand-edit.\n#pragma once\n#include <cstdint>\nstatic const uint32_t kSweepSymbols[] = {");
  for (size_t i = 0; i < count; ++i) {
    std::printf("0x%08lx,%s", static_cast<unsigned long>(words[i]), i % 8 == 7 ? "\n" : " ");
  }
  std::puts("};");
}
